/** 只读取宿主语言；zh 及地区变体用中文，其余和未设置时回退英文。 */
export function translate(message, values = {}) {
    const locale = app.ui.settings.getSettingValue("Comfy.Locale");
    const template = /^zh(?:[-_]|$)/i.test(locale ?? "") || !Object.hasOwn(english, message) ? message : english[message];
    return template.replace(/\{(\w+)\}/g, (match, key) => Object.hasOwn(values, key) ? String(values[key]) : match);
}

/** 订阅宿主语言事件；返回释放函数，由界面所属生命周期调用。 */
export function onLocaleChanged(callback) {
    app.ui.settings.addEventListener("Comfy.Locale.change", callback);
    return () => app.ui.settings.removeEventListener("Comfy.Locale.change", callback);
}

/** 在显示边界翻译已知接口错误；未知诊断保持原文，不改变 status/code。 */
export function errorMessage(error) {
    return translate(error.originalMessage ?? error.message, error.messageValues);
}
